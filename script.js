function getSavedLang() {
  try { return localStorage.getItem("portfolio_lang"); } catch (_) { return null; }
}
function saveLang(l) {
  try { localStorage.setItem("portfolio_lang", l); } catch (_) {}
}

function applyPortfolioLang(lang) {
  const t = I18N[lang] || I18N.uz;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const k = el.getAttribute("data-i18n");
    if (t[k] != null) el.textContent = t[k];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const k = el.getAttribute("data-i18n-html");
    if (t[k] != null) el.innerHTML = t[k];
  });
  const label = document.getElementById("langSwitchLabel");
  if (label) label.textContent = lang.toUpperCase();
  // TORNADO tilini ham o'zgartirish
  if (window.Tornado && typeof window.Tornado.setLang === "function") {
    window.Tornado.setLang(lang);
  }
  try { localStorage.setItem("tornado_lang", lang); } catch (_) {}
}

function hideLangModal() {
  const m = document.getElementById("langModal");
  if (m) m.classList.add("hidden");
}
function showLangModal() {
  const m = document.getElementById("langModal");
  if (m) m.classList.remove("hidden");
}

function selectLanguage(lang) {
  if (!I18N[lang]) lang = "uz";
  saveLang(lang);
  applyPortfolioLang(lang);
  hideLangModal();
  // Salom + avtomatik portfolio taqdimoti (har bir bo'lim ochiladi)
  const hi = {
    uz: "Assalomu alaykum! Men TORNADO, Abdunosirning shaxsiy yordamchisiman. Hozir portfolioni qisqacha tanishtirib chiqaman.",
    ru: "Здравствуйте! Я TORNADO, личный помощник Абдуносира. Сейчас кратко покажу портфолио.",
    en: "Hello! I'm TORNADO, Abdunosir's personal assistant. I'll briefly introduce the portfolio now."
  };
  const start = () => {
    if (!window.Tornado) { setTimeout(start, 400); return; }
    window.Tornado.setLang(lang);
    const afterGreet = () => {
      // Panel ochmasdan taqdimot — har bir menyu ochiladi
      if (typeof window.Tornado.startTour === "function") {
        window.Tornado.startTour();
      }
    };
    const p = (typeof window.Tornado.sayVoice === "function")
      ? window.Tornado.sayVoice(hi[lang] || hi.uz, lang)
      : window.Tornado.say(hi[lang] || hi.uz, lang);
    // say/sayVoice Promise qaytarishi mumkin
    if (p && typeof p.then === "function") p.then(afterGreet).catch(afterGreet);
    else setTimeout(afterGreet, 3500);
  };
  setTimeout(start, 700);
}

function switchPage(pageId) {
  const triggerMenu = document.querySelector(`[data-target="${pageId}"]`);
  if (triggerMenu) triggerMenu.click();
}

document.addEventListener("DOMContentLoaded", () => {
  // Navigatsiya
  const navItems = document.querySelectorAll(".nav-item");
  const pages = document.querySelectorAll(".page-section");

  function showPage(id, push) {
    pages.forEach((p) => p.classList.toggle("active", p.id === id));
    navItems.forEach((n) => n.classList.toggle("active", n.dataset.target === id));
    if (push !== false) {
      try { history.replaceState(null, "", "#" + id); } catch (_) {}
    }
    if (id === "skills" && typeof animateAllSkills === "function") animateAllSkills();
  }

  navItems.forEach((item) => {
    item.addEventListener("click", () => showPage(item.dataset.target));
    item.addEventListener("keydown", (e) => {
      if (e.key === "Enter" || e.key === " ") { e.preventDefault(); showPage(item.dataset.target); }
    });
  });
  window.addEventListener("hashchange", () => showPage(location.hash.slice(1) || "home", false));
  showPage(location.hash.slice(1) || "home", false);

  // Skills animatsiya
  const skillCards = document.querySelectorAll(".skill-card");
  function animateSkill(card) {
    const target = Number(card.dataset.percent);
    const bar = card.querySelector(".progress-bar span");
    const text = card.querySelector(".skill-percentage");
    cancelAnimationFrame(card._raf);
    bar.style.width = "0%";
    text.textContent = "0%";
    void bar.offsetWidth;
    bar.style.width = target + "%";
    const duration = 1200, start = performance.now();
    const step = (now) => {
      const t = Math.min((now - start) / duration, 1);
      text.textContent = Math.round(target * t) + "%";
      if (t < 1) card._raf = requestAnimationFrame(step);
    };
    card._raf = requestAnimationFrame(step);
  }
  window.animateAllSkills = function () {
    skillCards.forEach((card, i) => setTimeout(() => animateSkill(card), i * 150));
  };
  skillCards.forEach((card) => {
    card.addEventListener("click", () => animateSkill(card));
    card.addEventListener("keydown", (e) => {
      if (e.key === "Enter" || e.key === " ") { e.preventDefault(); animateSkill(card); }
    });
  });

  // Gallery
  const galleryMain = document.getElementById("galleryMain");
  document.querySelectorAll(".thumb").forEach((thumb) => {
    thumb.addEventListener("click", () => {
      document.querySelectorAll(".thumb").forEach((t) => t.classList.remove("active"));
      thumb.classList.add("active");
      if (galleryMain) {
        galleryMain.src = thumb.dataset.src;
        galleryMain.alt = thumb.dataset.alt || "";
      }
    });
  });

  // Til tanlash
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => selectLanguage(btn.dataset.lang));
  });
  const switchBtn = document.getElementById("langSwitchBtn");
  if (switchBtn) switchBtn.addEventListener("click", () => showLangModal());

  const msgBtn = document.getElementById("tornadoMsgBtn");
  if (msgBtn) {
    msgBtn.addEventListener("click", () => {
      const lang = getSavedLang() || "uz";
      const ask = (I18N[lang] && I18N[lang].msg_ask) || I18N.uz.msg_ask;
      if (window.Tornado) window.Tornado.ask(ask);
    });
  }

  // Har safar sahifa ochilganda / yangilanganda til tanlash majburiy
  const saved = getSavedLang();
  if (saved && I18N[saved]) {
    applyPortfolioLang(saved); // matnlarni oldindan qo'yamiz, lekin modal ochiq turadi
  }
  showLangModal();
});
